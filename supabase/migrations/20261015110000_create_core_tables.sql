create table public.agents (
  id bigint generated by default as identity primary key,
  name text not null,
  balance numeric not null default 0,
  daily_limit numeric not null default 0,
  transaction_limit numeric not null default 0,
  active boolean not null default true,
  spent_today numeric not null default 0,
  api_key text not null unique,
  allowed_merchants text[] not null default '{}'::text[],
  created_at timestamptz not null default now()
);

create table public.transactions (
  id bigint generated by default as identity primary key,
  agent_id bigint not null references public.agents(id),
  merchant text not null,
  amount numeric not null,
  status text not null,
  reason text not null,
  created_at timestamptz not null default now()
);